/*
  hud_config.h — настройки сборки HUD
*/
#ifndef HUD_CONFIG_H
#define HUD_CONFIG_H

/* ---- Источник данных ----
   HUD_SRC_BLE  — сырые CAN-кадры от сниффера / BLE-гейта по BLE (протокол ACL)
   HUD_SRC_TWAI — свой трансивер CAN Pal (TJA1051T/3) прямо на шине I-CAN,
                  встроенный контроллер TWAI в режиме LISTEN_ONLY
   HUD_SRC_FAKE — встроенный генератор кадров, для проверки без машины
   HUD_SRC_AUTO — работают оба: если по своему трансиверу (TWAI) идут кадры —
                  используется он, BLE отключается; нет кадров по CAN дольше
                  HUD_AUTO_CAN_HOLD_MS — используется BLE от сниффера / гейта
   Декодер и экран одни и те же, меняется только откуда приходят кадры. */
#define HUD_SRC_BLE          0
#define HUD_SRC_TWAI         1
#define HUD_SRC_FAKE         2
#define HUD_SRC_AUTO         3
#define HUD_DATA_SOURCE      HUD_SRC_AUTO
#define HUD_AUTO_CAN_HOLD_MS 1000   /* AUTO: столько без кадров по CAN — переходим на BLE */

/* BLE-защита: код доступа задаётся в secrets.h (шаблон secrets.example.h).
   Столько неудач сопряжения подряд — на экране подсказка «сопряжение не принято» */
#define HUD_BLE_PAIR_MSG_AFTER 3

/* ---- TWAI (для HUD_SRC_TWAI и HUD_SRC_AUTO) ----
   Пины по таблице GPIO платы Waveshare ESP32-S3-Touch-LCD-3.49: GPIO1 и GPIO2
   выведены на разъём и не заняты ничем (LCD, SD, IMU/RTC, I2S, UART).
   RX — единственный провод данных от CAN Pal к плате.
   TX драйвер TWAI требует обязательно, но в LISTEN_ONLY он всегда
   рецессивный. К CAN Pal его НЕ подключать: вывод TX на CAN Pal оставить
   свободным (внутренняя подтяжка TJA1051 держит рецессив), SLNT — на 3V3.
   Пин TX — свободный, ни к чему не подключённый (на разъёме GPIO2 оставить пустым). */
#define HUD_CAN_RX_PIN       1
#define HUD_CAN_TX_PIN       2
#define HUD_CAN_BITRATE_K    500    /* I-CAN MLB-Evo — 500 кбит/с */

/* совместимость со старым переключателем */
#ifdef HUD_FAKE_FRAMES
#if HUD_FAKE_FRAMES
#undef  HUD_DATA_SOURCE
#define HUD_DATA_SOURCE      HUD_SRC_FAKE
#endif
#endif

/* 1 = мигать строго по биту *_Kombi_Takt (фаза как на приборке).
   0 = бит такта используется только как признак "поворотник включён",
       мигаем своим таймером 500/500 мс (на случай рваного такта по BLE). */
#define HUD_BLINK_FROM_TAKT  1

/* Имя сниффера в эфире */
#define HUD_SNIFFER_NAME     "S3-CAN-Sniffer"

/* Lane Assist: LDW_02 0x397 (~80 мс). В ACL — интервал, а не onchange:
   при onchange стабильное состояние не присылается, и значок гас бы по таймауту. */
#define LKA_MIN_INTERVAL_MS  500

/* ---- Яркость подсветки дисплея (0..255): освещённость x колёсико ----
   Два входа, оба от машины:
     освещённость — датчик RLS_01: LS_Helligkeit_FW (до 6126 лк), выше — по
       RLS_Vorfeldhelligkeit_Boost (до ~30000 лк на прямом солнце);
     колёсико подсветки — BCM1_04.BCM1_Stellgroesse_Kl_58s (1..100).
   Четыре угла — подсветка при минимальной / максимальной освещённости и колёсике
   на минимуме / максимуме; между углами — плавно (по освещённости — логарифмически,
   как видит глаз; по колёсику — линейно). Ниже 90 экран не виден. */
#define HUD_BR_DARK_WHEEL_MIN     90     /* темно,  колёсико на минимуме  */
#define HUD_BR_DARK_WHEEL_MAX     110    /* темно,  колёсико на максимуме */
#define HUD_BR_BRIGHT_WHEEL_MIN   200    /* солнце, колёсико на минимуме  */
#define HUD_BR_BRIGHT_WHEEL_MAX   255    /* солнце, колёсико на максимуме */
#define HUD_LIGHT_LUX_DARK        0      /* «минимальная освещённость», лк  */
#define HUD_LIGHT_LUX_BRIGHT      30000  /* «максимальная» — прямое солнце, лк */
#define HUD_WHEEL_DEFAULT         100    /* колёсико, пока его положение не пришло, % */
#define HUD_BRIGHT_NO_DATA    170    /* пока нет данных о яркости (и без связи)       */
#define HUD_BRIGHT_STEP       4      /* плавность: шаг изменения за 50 мс             */

/* ---- Запасной датчик света: фоторезистор на GPIO5 (ADC1) ----
   Схема: фоторезистор 3V3 — GPIO5, резистор 10 кОм GPIO5 — GND, 100 нФ GPIO5 — GND.
   Используется, когда нет данных RLS_01 по CAN. Включается и калибруется из меню
   (Прочее → Датчик: закрыть датчик → «Темно», посветить фонариком → «Светло»). */
#define HUD_LDR_PIN           5      /* вход АЦП (только ADC1: GPIO1…10)               */
#define HUD_LDR_ON            0      /* первый запуск: 1 — датчик включён              */
#define HUD_LDR_DARK_MV       150    /* калибровка по умолчанию: «темно», мВ           */
#define HUD_LDR_BRIGHT_MV     2500   /* …и «светло», мВ                                */
#define HUD_LDR_MIN_SPAN_MV   300    /* минимальная разница «светло»−«темно» при калибровке, мВ */

/* ---- Обновление прошивки по Wi-Fi (OTA) ----
   Удержите BOOT HUD_OTA_HOLD_MS на стоящей машине: HUD перезагрузится в режим
   обновления (точка доступа Wi-Fi + страница http://192.168.4.1). Нужна таблица
   разделов с двумя приложениями — Инструменты → Partition Scheme →
   «16M Flash (3MB APP/9.9MB FATFS)». Пароль точки — HUD_OTA_PASS в secrets.h. */
#define HUD_OTA_BTN_PIN       0          /* кнопка BOOT (GPIO0)                              */
#define HUD_OTA_HOLD_MS       1500       /* сколько держать BOOT                              */
#define HUD_OTA_SSID          "HUD-Update"
#define HUD_OTA_TIMEOUT_MS    300000     /* режим обновления сам закрывается через 5 мин без загрузки */

/* ---- Язык и единицы ----
   Значения для самого первого запуска; дальше — из меню (сохраняются в NVS). */
#define HUD_LANG_RU    0
#define HUD_LANG_EN    1
#define HUD_UNITS_KM   0     /* км/ч, км, м                               */
#define HUD_UNITS_MI   1     /* mph, mi, ft (скорость ACC/лимитера тоже)  */

#define HUD_LANG       HUD_LANG_RU
#define HUD_UNITS      HUD_UNITS_KM
#define HUD_VOLUME_GAL 0     /* «сколько заправить»: 0 — литры, 1 — галлоны США (дальше — меню) */
#define HUD_TANK_L     54    /* объём бака, л (A4 B9 — 54 л; пока константа)              */

/* ---- Звук (кодек ES8311 + усилитель на плате) ----
   Играет в своей задаче, от отрисовки не зависит. Звуки — tools/sounds/,
   пересборка: python tools/make_sounds.py */
#define HUD_SOUND_ENABLE           1     /* 0 — звук полностью выключен (кодек не трогается) */
#define HUD_SOUND_STARTUP          1     /* стартовый звук при включении                     */
#define HUD_SOUND_STARTUP_DELAY_MS 300   /* пауза после запуска перед стартовым звуком        */
#define HUD_SOUND_VOLUME           25    /* громкость 0..100                                  */

/* ---- Бар ускорения (по CAN) ----
   По нижнему краю экрана под стрелкой навигации квадраты расходятся из центра: зелёные — разгон,
   красные — торможение. Источник:
     1) ESP_02.ESP_Laengsbeschl (0x101) — продольное ускорение от ESP, если
        этот кадр есть на I-CAN;
     2) иначе — производная скорости Kombi_01.KBI_angez_Geschw (0x30B).
   Полная шкала разгона — 0..HUD_ACCEL_REF_KMH за HUD_ACCEL_REF_SEC с
   (100 км/ч за 9 с = 3.09 м/с²), торможения — HUD_BRAKE_FULL_MS2 (6 м/с² —
   резкое, но не экстренное торможение; экстренное 8-10 упрётся в край). */
#define HUD_ACCEL_BAR         0      /* бар ускорения при первом запуске (дальше — меню) */
#define HUD_ACCEL_REF_KMH     100
#define HUD_ACCEL_REF_SEC     9
#define HUD_BRAKE_FULL_MS2    6
#define HUD_ACCEL_ON          0.40f  /* м/с²: бар загорается выше этого (сглаженного) ускорения */
#define HUD_ACCEL_OFF         0.20f  /* м/с²: и гаснет ниже этого — гистерезис, без мигания  */
#define HUD_ACCEL_SMOOTH_MS   600    /* сглаживание, мс                                       */
#define HUD_ACCEL_GAIN        0.25f  /* чувствительность бара: 0.25 — в 4 раза спокойнее,
                                        т.е. полная шкала = 12.4 м/с² разгона / 24 м/с² торможения */

/* ---- Полоска расхода топлива (по CAN) ----
   Правый край экрана, 5 px, тёмно-серая, растёт снизу вверх: 0..HUD_FUEL_FULL
   л/100 км. Показывается от HUD_FUEL_ON_KMH, пропадает ниже HUD_FUEL_OFF_KMH;
   больше HUD_FUEL_FULL — мигает.
   Источник среднего: бортовой компьютер приборки, BAP_BC (LSG 0x0F, 0x17330F10),
   «с момента запуска». Мгновенного расхода на I-CAN нет: Motor_04.MO_KVS (0x107)
   используется, только если такой кадр окажется на шине. */
#define HUD_FUEL_BAR          1
#define HUD_FUEL_FULL         20     /* л/100 км */
#define HUD_FUEL_ON_KMH       35     /* полоска появляется от этой скорости...         */
#define HUD_FUEL_OFF_KMH      30     /* ...и пропадает ниже этой (гистерезис, без мигания) */
#define HUD_FUEL_AVG          1      /* при первом запуске: 1 средний, 0 мгновенный (дальше — меню).
                                        Средний — «с момента запуска» приборки (BAP_BC), с любой скорости.
                                        Мгновенный — только если на шине есть Motor_04 (на I-CAN не найден) */

/* ---- Журнал на SD-карту платы ----
   1 — всё, что идёт в Serial, дублируется на SD (SPI: CS 38, MOSI 39, MISO 40,
   SCLK 41). Запись начинается только после получения даты и времени по CAN
   (Diagnose_01, 0x6B2): /logs/ГГГГ-ММ-ДД/log_ЧЧ_N.txt, каждый час — новый файл,
   N растёт при перезапуске в тот же час. Строки — с меткой [ЧЧ:ММ:СС.мс].
   Карты нет — пишется только в Serial. */
#define HUD_LOG_TO_SD         0      /* по умолчанию выключено */
#define HUD_LOG_SD_MAX_MB     50     /* больше — новый файл (N+1) в том же часе */

/* ---- Знаки ограничения и превышение ----
   Основной знак: PSD явный знак (прогноз маршрута MIB, 0x462-0x464) -> VZE_01
   -> PSD «по правилам». PSD работает и тогда, когда приборка знаков не показывает. */
#define HUD_PSD_LIMITS            1      /* знаки PSD при первом запуске (дальше — меню)      */
#define HUD_VZE_SIGNS             1      /* знаки VZE_01 при первом запуске (дальше — меню)   */
#define HUD_PSD_LEGAL_DELAY_MS    1000   /* задержка смены «явный знак» -> «по правилам»      */
#define HUD_SIGN_CYCLE_MS         1000   /* несколько знаков — по очереди, каждый столько мс  */
/* Допуск превышения, км/ч. Обводка цифр скорости начинает проявляться при
   превышении HUD_OVERSPEED_START % допуска и становится полностью красной
   на 100 % (по умолчанию: 15 км/ч сверх знака — появляется, 20 — красная). */
#define HUD_OVERSPEED_TOL_KMH     20
#define HUD_OVERSPEED_START       75     /* % допуска */

/* ---- Side Assist (SWA_01, 0x30F) ----
   Полоски полос на значке ассистентов — красные, даже если Lane Assist и ACC
   выключены: машина в мёртвой зоне — полоска горит, попытка перестроения
   (поворотник при машине сбоку) — мигает и HUD пикает. */
#define HUD_SWA               1
#define HUD_SWA_BEEP          1      /* пикать при предупреждении                    */
#define HUD_SWA_BEEP_REPEAT_MS 1200  /* пока предупреждение держится — повторять    */

/* ---- Тачскрин и меню настроек ----
   Двойное касание экрана (или одиночное, см. HUD_MENU_DOUBLE_TAP) — меню: язык, единицы, источник знаков (VZE / PSD),
   бар ускорения. Выбор сохраняется во флеше (NVS) и переживает перезапуск;
   значения HUD_LANG / HUD_UNITS / HUD_PSD_LIMITS / HUD_ACCEL_BAR / HUD_SOUND_VOLUME / HUD_OVERSPEED_TOL_KMH — только для
   самого первого запуска. Меню открывается по «касание + отпускание», поэтому
   залипшее касание его не открывает. 0 — тач не опрашивается, меню нет. */
#define HUD_TOUCH_ENABLE      1
#define HUD_MENU_TIMEOUT_MS   10000  /* меню закрывается само через 10 с без касаний */
#define HUD_MENU_DOUBLE_TAP   1      /* 1 — меню по двойному касанию, 0 — по одиночному */
#define HUD_DOUBLE_TAP_MS     400    /* окно для второго касания, мс                   */
#define HUD_MENU_ONLY_STOPPED 1      /* безопасность: меню только на стоящей машине;
                                        тронулись — открытое меню закрывается          */
#define HUD_MENU_MAX_KMH      0      /* «стоит» — скорость не больше этой, км/ч        */

/* ---- Журналы в Serial по типам: 1 — печатать, 0 — нет ---- */
#define HUD_LOG_BLE    1   /* [BLE]  подключение к снифферу, запись и проверка ACL, ошибки   */
#define HUD_LOG_TWAI   1   /* [TWAI] запуск контроллера, ошибки, восстановление шины        */
#define HUD_LOG_SRC    1   /* [src]  какой источник сейчас используется (AUTO)              */
#define HUD_LOG_STAT   0   /* [BLE]/[TWAI] раз в 10 с: кадров, потери, макс. пауза скорости   */
#define HUD_LOG_CAN    0   /* [CAN]  раз в 10 с: счётчики и последние данные по каждому ID    */
#define HUD_LOG_DIM    0   /* [dim]  раз в 10 с: данные Dimmung_01 и выставленная подсветка   */
#define HUD_LOG_BAP    0   /* [nav]/[bap] смена манёвра, неизвестные коды, прочие функции навигации */
#define HUD_LOG_HUD    1   /* [hud]  построение экрана, пропадание скорости по таймауту       */
#define HUD_LOG_LVGL   1   /* [LVGL] сообщения LVGL (нужен ещё LV_USE_LOG 1 в lv_conf.h)      */

#endif
